#[cfg(test)]
mod tests {
    use super::{Sha256, hex_digest};

    #[test]
    fn matches_known_vectors() {
        assert_eq!(
            hex_digest(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            hex_digest(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            hex_digest(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
    }

    #[test]
    fn streaming_matches_one_shot() {
        let payload: Vec<u8> = (0..1000u32).map(|value| (value % 251) as u8).collect();
        let mut hasher = Sha256::new();
        for chunk in payload.as_chunks::<7>().0 {
            hasher.update(chunk);
        }
        let rest = payload.len() / 7 * 7;
        hasher.update(&payload[rest..]);
        assert_eq!(hasher.finish_hex(), hex_digest(&payload));
    }

    #[test]
    fn matches_nist_million_byte_vector() {
        let payload = vec![0x61u8; 1_000_000];
        assert_eq!(
            hex_digest(&payload),
            "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0"
        );
    }

    #[test]
    fn boundary_lengths_are_stable() {
        for length in [55usize, 56, 57, 63, 64, 65, 119, 120] {
            let payload = vec![0x61u8; length];
            assert_eq!(hex_digest(&payload).len(), 64, "长度 {length}");
        }
    }
}
