//! 会话运行态证据：一条会话此刻是否真的在跑，以及这份证据有多新鲜。
//!
//! 「在跑」不能只由界面按自己的投影推算：执行进程消失、轮次租约过期、provider 长时间
//! 不吐首字，都会留下一个没有任何执行者的轮次，而界面照旧转圈。本模块只定义证据的形状；
//! 读取在 ingress 实现里，判定在路由层。证据读不出来时必须显式失败，读侧据此降级，
//! 绝不用「未知」冒充「在跑」。

/// 一条会话的运行态证据。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GatewaySessionLive {
    /// 是否存在带租约且租约未过期的在跑轮次。
    ///
    /// 只认「带租约且未过期」的行：没有租约的行说明这一轮没有执行者，不是证据。
    pub running: bool,
    /// 未过期租约的剩余时长（毫秒）；`running` 为假时为空。
    pub lease_remaining_ms: Option<u64>,
    /// 该会话 durable 事件尾序号。
    pub last_frame_sequence: u64,
    /// 距离最后一次活动（最后一条事件写入）的静默时长（毫秒）。
    pub idle_for_ms: u64,
    /// 已被接受、但还没有任何执行者领取的排队轮次数。
    ///
    /// 刚提交的轮次会先停在排队态再被领取，这段时间没有租约是正常的：读侧据此区分
    /// 「还没开始」与「已经没有执行者」，不得把排队读成证据过期。
    pub queued_turns: u64,
}
